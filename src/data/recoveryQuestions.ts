/**
 * Returns a slice of questions for streak recovery avoiding previously used question IDs if possible.
 */
export function getRecoveryQuestions(count: number, usedIds: string[] = []): RecoveryQuestion[] {
  const unused = RECOVERY_QUESTIONS.filter((q) => !usedIds.includes(q.id));
  const pool = unused.length >= count ? unused : [...unused, ...RECOVERY_QUESTIONS.filter((q) => usedIds.includes(q.id))];

  // Shuffle pool predictably for variety
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, Math.max(1, count));
}
